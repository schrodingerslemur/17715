static inline uint16_t speck_rotr(uint16_t v, int r) {
    return (uint16_t)((v >> r) | (v << (16 - r)));
}
static inline uint16_t speck_rotl(uint16_t v, int r) {
    return (uint16_t)((v << r) | (v >> (16 - r)));
}

// Expand a 64-bit key into its SPECK_ROUNDS round keys.
static inline void speck_schedule(const uint16_t key[4],
                                  uint16_t rk[SPECK_ROUNDS]) {
    uint16_t l[SPECK_ROUNDS + 3];
    rk[0] = key[0];
    l[0] = key[1];
    l[1] = key[2];
    l[2] = key[3];
    for (int i = 0; i < SPECK_ROUNDS - 1; i++) {
        l[i + 3] = (uint16_t)((rk[i] + speck_rotr(l[i], SPECK_ALPHA)) ^ i);
        rk[i + 1] = (uint16_t)(speck_rotl(rk[i], SPECK_BETA) ^ l[i + 3]);
    }
}

// Decrypt one block with the given 64-bit key: SPECK_ROUNDS inverse rounds,
// each undoing  x = (ror(x,a) + y) ^ k;  y = rol(y,b) ^ x.
static inline block speck_decrypt(const uint16_t key[4], block ct) {
    uint16_t rk[SPECK_ROUNDS];
    speck_schedule(key, rk);
    uint16_t x = (uint16_t)(ct >> 16), y = (uint16_t)ct;
    for (int i = SPECK_ROUNDS - 1; i >= 0; i--) {
        y = speck_rotr((uint16_t)(y ^ x), SPECK_BETA);
        x = speck_rotl((uint16_t)((uint16_t)(x ^ rk[i]) - y), SPECK_ALPHA);
    }
    return ((block)x << 16) | y;
}

